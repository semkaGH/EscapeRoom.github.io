import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox", "--disable-gpu-sandbox", "--use-gl=swiftshader"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on("console", m => { if (m.type() === "error") errors.push(m.text()); console.log("CONSOLE", m.type(), m.text()); });
page.on("pageerror", e => { errors.push(String(e)); console.log("PAGEERROR", String(e)); });
page.on("requestfailed", r => console.log("REQUESTFAILED", r.url(), r.failure()?.errorText));
await page.goto("http://127.0.0.1:4173/?verify=1", { waitUntil: "networkidle", timeout: 60000 });
await page.waitForFunction(() => window.__GAME_READY__ === true, null, { timeout: 30000 });
await page.waitForTimeout(700);
mkdirSync("verification-shots", { recursive: true });
await page.screenshot({ path: "verification-shots/debug-title.png" });
console.log("GL", await page.evaluate(() => {
  const c = document.querySelector("canvas");
  const gl = c.getContext("webgl2") || c.getContext("webgl");
  const px = new Uint8Array(4);
  gl.readPixels((c.width/2)|0, (c.height/2)|0, 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, px);
  return { attrs: gl.getContextAttributes(), center: [...px] };
}));
await page.keyboard.press("Space");
await page.waitForTimeout(500);
await page.screenshot({ path: "verification-shots/debug-gameplay.png" });
await page.keyboard.press("KeyF");
await page.waitForTimeout(500);
await page.screenshot({ path: "verification-shots/debug-flashlight.png" });
console.log("DEBUG", await page.evaluate(() => window.__gameDebug?.()));
console.log("ERRORS", errors);
await browser.close();
